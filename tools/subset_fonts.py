#!/usr/bin/env python3
"""Subset the Fusion Pixel 12px proportional BDF fonts to the characters the game needs.

Usage:  python -I tools/subset_fonts.py   (paths are resolved from the script's location)
Python 3 standard library only.

Reads   game/locale/strings.csv
        third_party/fusion-pixel-font-12px-proportional/fusion-pixel-12px-proportional-{ko,zh_hans}.bdf
Writes  game/fonts/asylum-ko.bdf, game/fonts/asylum-zh_hans.bdf (BDF 2.1, header kept, CHARS updated)
        game/fonts/OFL.txt, OFL-ark-pixel.txt, LICENSE-galmuri.txt, README.txt

Character sets:
  ko       en + ko columns (English and Korean UI use Korean glyph forms)
  zh_hans  zh_CN column
  both     language names, printable ASCII 0x21-0x7E, CJK punctuation used anywhere
A character missing from its flavour's font but present in the other one is added to the other
subset (the game falls back to the other flavour). Exit status 1 when a character that the
original Asylum bitmap font cannot draw is missing from both fonts.
"""

import csv
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "game" / "locale" / "strings.csv"
SRC_DIR = ROOT / "third_party" / "fusion-pixel-font-12px-proportional"
OUT_DIR = ROOT / "game" / "fonts"
FONT_VERSION = "2026.09.25"
FLAVOURS = ("ko", "zh_hans")
LANG_KEYS = ("LANG_EN", "LANG_KO", "LANG_ZH")


def original_glyph(c):
    """Mirror of asylum_core::font::original_glyph (characters of the original FSPChars font)."""
    return (
        "0" <= c <= "9"
        or "A" <= c <= "Z"
        or "a" <= c <= "z"
        or c in "•-–?←%✓✗.,!'’"
    )


def is_cjk_punctuation(c):
    o = ord(c)
    return (
        0x3000 <= o <= 0x303F  # CJK symbols and punctuation
        or 0xFF00 <= o <= 0xFFEF  # half-width and full-width forms
        or 0x2010 <= o <= 0x2027  # dashes, quotes, ellipsis, middle dots
        or 0x2030 <= o <= 0x205E
        or o in (0x00B7, 0x30FB)
    )


def visible(c):
    return not c.isspace() and ord(c) >= 0x20 and not (0x7F <= ord(c) < 0xA0)


def read_strings():
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.reader(f))
    header = [h.strip() for h in rows[0]]
    col = {name: header.index(name) for name in ("key", "en", "ko", "zh_CN")}
    table = {}
    for row in rows[1:]:
        if not any(cell.strip() for cell in row):
            continue
        row = row + [""] * (len(header) - len(row))
        table[row[col["key"]].strip()] = {
            lang: row[col[lang]].replace("\\n", "\n") for lang in ("en", "ko", "zh_CN")
        }
    return table


def wanted_chars(table):
    ko, zh, both = set(), set(), set()
    for cells in table.values():
        ko.update(cells["en"] + cells["ko"])
        zh.update(cells["zh_CN"])
        both.update(c for c in "".join(cells.values()) if is_cjk_punctuation(c))
    for key in LANG_KEYS:
        both.update("".join(table.get(key, {}).values()))
    both.update(chr(o) for o in range(0x21, 0x7F))
    ko |= both
    zh |= both
    return {"ko": {c for c in ko if visible(c)}, "zh_hans": {c for c in zh if visible(c)}}


class Bdf:
    """Source BDF split into header lines (without CHARS) and glyph blocks by encoding."""

    def __init__(self, path):
        lines = path.read_text(encoding="utf-8").splitlines()
        if not lines or not lines[0].startswith("STARTFONT 2.1"):
            raise ValueError(f"{path}: not a BDF 2.1 file")
        self.path = path
        self.header = []
        self.glyphs = []  # (encoding, [lines]) in file order
        self.default_char = None
        i = 0
        while i < len(lines) and not lines[i].startswith("STARTCHAR"):
            line = lines[i]
            if line.startswith("DEFAULT_CHAR"):
                self.default_char = int(line.split()[1])
            if not line.startswith("CHARS ") and line != "ENDFONT":
                self.header.append(line)
            i += 1
        block = None
        for line in lines[i:]:
            if line.startswith("STARTCHAR"):
                block = [line]
            elif block is not None:
                block.append(line)
                if line == "ENDCHAR":
                    enc = next(int(l.split()[1]) for l in block if l.startswith("ENCODING "))
                    self.glyphs.append((enc, block))
                    block = None
        self.by_code = {enc: blk for enc, blk in self.glyphs if enc >= 0}

    def write_subset(self, path, codes):
        keep = set(codes)
        if self.default_char is not None:
            keep.add(self.default_char)
        blocks = [blk for enc, blk in self.glyphs if enc in keep]
        out = [self.header[0], "COMMENT Subset for Asylum for Windows (Godot port), generated by tools/subset_fonts.py"]
        out += self.header[1:]
        out.append(f"CHARS {len(blocks)}")
        for blk in blocks:
            out += blk
        out.append("ENDFONT")
        path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
        return len(blocks)


def validate(path):
    """Structural BDF 2.1 check of a written file; returns the set of encodings."""
    lines = path.read_text(encoding="utf-8").splitlines()
    assert lines[0] == "STARTFONT 2.1" and lines[-1] == "ENDFONT", path
    chars = next(int(l.split()[1]) for l in lines if l.startswith("CHARS "))
    codes = set()
    i = 0
    count = 0
    while i < len(lines):
        if lines[i].startswith("STARTCHAR"):
            count += 1
            j = lines.index("BITMAP", i)
            fields = {l.split()[0]: l.split()[1:] for l in lines[i + 1 : j]}
            enc = int(fields["ENCODING"][0])
            w, h = int(fields["BBX"][0]), int(fields["BBX"][1])
            assert "DWIDTH" in fields, (path, enc)
            rows = lines[j + 1 : j + 1 + h]
            assert lines[j + 1 + h] == "ENDCHAR", (path, enc)
            assert all(len(r) == max(1, (w + 7) // 8) * 2 and int(r, 16) >= 0 for r in rows), (path, enc)
            codes.add(enc)
            i = j + 1 + h
        i += 1
    assert count == chars, (path, count, chars)
    return codes


README = """CJK glyph subsets for Asylum for Windows (Godot port)
=====================================================

asylum-ko.bdf       Korean glyph forms (English and Korean UI)
asylum-zh_hans.bdf  Simplified Chinese glyph forms (Chinese UI; the Chinese language name in
                    every UI)

Source:   Fusion Pixel Font, 12px proportional, BDF release {version}
          https://github.com/TakWolf/fusion-pixel-font
          Copyright (c) 2022, TakWolf (https://takwolf.com)
          The glyphs used here come from these fonts, which Fusion Pixel Font combines:
          - Ark Pixel Font, https://github.com/TakWolf/ark-pixel-font
            Copyright (c) 2021, TakWolf (https://takwolf.com) - base glyphs
          - Galmuri 2.40.4, https://github.com/quiple/galmuri
            Copyright (c) 2019-2025 Lee Minseo (quiple@quiple.dev) - Hangul syllables
License:  SIL Open Font License, Version 1.1, no Reserved Font Names
          (OFL.txt, OFL-ark-pixel.txt, LICENSE-galmuri.txt).

These files are subsets ({ko} and {zh} glyphs) holding only the characters used by
game/locale/strings.csv, the language names, printable ASCII and the CJK punctuation in use.
They were generated by tools/subset_fonts.py; do not edit them by hand. After changing
strings.csv run:  python -I tools/subset_fonts.py

Characters the original Asylum bitmap font has (digits, letters, . , ! ' ? - % and its symbols)
are always drawn with the original glyphs. Every other glyph is restyled at run time like the
original font (emboldened strokes, 1 px outline, original green palette).
"""


def main():
    # Console code pages may not encode every reported character.
    sys.stdout.reconfigure(errors="backslashreplace")
    table = read_strings()
    wanted = wanted_chars(table)
    fonts = {fl: Bdf(SRC_DIR / f"fusion-pixel-12px-proportional-{fl}.bdf") for fl in FLAVOURS}
    codes = {fl: set() for fl in FLAVOURS}
    borrowed, covered_by_original, missing = [], set(), set()
    for fl in FLAVOURS:
        other = FLAVOURS[1 - FLAVOURS.index(fl)]
        for c in sorted(wanted[fl]):
            o = ord(c)
            if o in fonts[fl].by_code:
                codes[fl].add(o)
            elif o in fonts[other].by_code:
                codes[other].add(o)
                borrowed.append((fl, other, c))
            elif original_glyph(c):
                covered_by_original.add(c)
            else:
                missing.add(c)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    counts = {}
    for fl in FLAVOURS:
        out = OUT_DIR / f"asylum-{fl}.bdf"
        counts[fl] = fonts[fl].write_subset(out, codes[fl])
        written = validate(out)
        assert codes[fl] <= written, out
        print(f"{out}: {counts[fl]} glyphs ({len(wanted[fl])} characters wanted)")
    shutil.copyfile(SRC_DIR / "OFL.txt", OUT_DIR / "OFL.txt")
    shutil.copyfile(SRC_DIR / "LICENSES" / "ark-pixel" / "OFL.txt", OUT_DIR / "OFL-ark-pixel.txt")
    shutil.copyfile(SRC_DIR / "LICENSES" / "galmuri" / "LICENSE.txt", OUT_DIR / "LICENSE-galmuri.txt")
    (OUT_DIR / "README.txt").write_text(
        README.format(version=FONT_VERSION, ko=counts["ko"], zh=counts["zh_hans"]), encoding="utf-8", newline="\n"
    )

    def show(chars):
        return " ".join(f"U+{ord(c):04X}({c})" for c in sorted(chars))

    for fl, other, c in borrowed:
        print(f"note: U+{ord(c):04X}({c}) is not in the {fl} font; taken from {other}")
    if covered_by_original:
        print("not in either font, drawn with the original Asylum font (fine):", show(covered_by_original))
    if missing:
        print("ERROR: missing from both fonts:", show(missing))
        return 1
    print("characters missing from both fonts: none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
